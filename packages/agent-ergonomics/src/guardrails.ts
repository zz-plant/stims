/**
 * Generates the guardrails page — the rules a repo enforces — from the guard
 * scripts themselves, and checks that the committed page is current.
 *
 * Guard scripts encode a repo's unwritten rules, and the good ones explain
 * their own rationale in a docblock. That rationale is only reachable by
 * opening the script, so in practice contributors meet each rule by tripping
 * it. This surfaces the explanations that already exist as one page a person
 * can read before writing code, with the gate each guard runs in read from
 * the gate plan rather than from any composite command string.
 *
 * Generated, not written, for the same reason the script index is: a
 * hand-kept list of guards drifts the moment someone adds one, and a stale
 * list of rules is worse than none. `--check` fails when the committed page
 * is out of date, so the docblock is the single source of truth.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import type { AgentErgonomicsConfig } from './config.ts';
import type { Command } from './context.ts';
import { parseDocblock } from './docblock.ts';
import { gateScriptNames } from './gate.ts';
import { readPackageScripts } from './scripts-index.ts';

export type Guard = {
  name: string;
  summary: string;
  rest: string;
  gate: string;
};

export type GuardrailsRender = {
  rendered: string;
  guards: Guard[];
  undocumented: string[];
};

const escapeRegExp = (text: string) =>
  text.replace(/[.*+?^${}()|[\]\\]/gu, '\\$&');

export function renderGuardrails(
  config: AgentErgonomicsConfig,
  scripts: Record<string, string>,
  root: string,
): GuardrailsRender {
  const { guardrails, gate, commands, runner, scriptsDir } = config;
  const quickGuards = gateScriptNames(gate, 'quick');
  const fullGuards = gateScriptNames(gate, 'full');
  const membership = (name: string) => {
    if (quickGuards.has(name)) return `\`${guardrails.gateCommands.quick}\``;
    if (fullGuards.has(name)) return `\`${guardrails.gateCommands.full}\``;
    return 'on demand';
  };

  const targetPattern = new RegExp(
    `${escapeRegExp(scriptsDir)}\\/([^\\s/]+\\.(?:ts|mjs|js))`,
    'u',
  );
  const docblock = (command: string) => {
    const file = command.match(targetPattern)?.[1];
    if (!file) return null;
    let text: string;
    try {
      text = readFileSync(join(root, scriptsDir, file), 'utf8');
    } catch {
      return null;
    }
    return parseDocblock(text, { openerWithin: guardrails.docblockWindow });
  };

  const guards: Guard[] = [];
  const undocumented: string[] = [];
  const excluded = new Set(guardrails.exclude);
  for (const [name, command] of Object.entries(scripts)) {
    if (!name.startsWith(guardrails.guardPrefix)) continue;
    if (excluded.has(name)) continue;
    const doc = docblock(command);
    if (!doc?.summary) {
      undocumented.push(name);
      continue;
    }
    guards.push({
      name,
      summary: doc.summary,
      rest: doc.rest,
      gate: membership(name),
    });
  }
  guards.sort((a, b) => a.name.localeCompare(b.name));

  const lines: string[] = [
    `<!-- Generated by \`${commands.generateGuardrails}\`. Do not edit by hand:`,
    '     each entry comes from the docblock atop its guard script. -->',
    '',
    `# ${guardrails.title}`,
    '',
    ...guardrails.intro,
    '',
    '| Guard | Runs in | Enforces |',
    '| --- | --- | --- |',
  ];
  for (const guard of guards) {
    const summary = guard.summary.replace(/\|/gu, '\\|');
    lines.push(
      `| [\`${guard.name}\`](#${guard.name.replace(':', '')}) | ${guard.gate} | ${summary} |`,
    );
  }
  lines.push('', '---', '');
  for (const guard of guards) {
    lines.push(`## ${guard.name}`, '', guard.summary, '');
    if (guard.rest) lines.push(guard.rest, '');
    lines.push(`Run it directly: \`${runner} ${guard.name}\``, '');
  }
  if (undocumented.length > 0) {
    lines.push(
      '---',
      '',
      '## Not yet documented',
      '',
      'These guards have no docblock to generate from, so their rationale still',
      'lives only in the code. Adding one here is a good first contribution:',
      '',
      ...undocumented.sort().map((name) => `- \`${name}\``),
      '',
    );
  }
  const rendered = `${lines
    .join('\n')
    .replace(/\n{3,}/gu, '\n\n')
    .trim()}\n`;
  return { rendered, guards, undocumented };
}

/** `guardrails [--check]` */
export const runGuardrails: Command = (args, { config, cwd, io }) => {
  const { output } = config.guardrails;
  const generate = config.commands.generateGuardrails;
  const { rendered, guards, undocumented } = renderGuardrails(
    config,
    readPackageScripts(cwd),
    cwd,
  );
  const out = join(cwd, output);

  if (args.includes('--check')) {
    let current: string;
    try {
      current = readFileSync(out, 'utf8');
    } catch {
      io.error(`${output} is missing. Run \`${generate}\`.`);
      return 1;
    }
    if (current !== rendered) {
      io.error(
        `${output} is out of date with the guard docblocks.\n` +
          `Run \`${generate}\` and commit the result.`,
      );
      return 1;
    }
    io.log(`${output} is current.`);
    return 0;
  }

  writeFileSync(out, rendered);
  io.log(
    `Wrote ${output} — ${guards.length} guards documented, ${undocumented.length} pending.`,
  );
  return 0;
};
