/**
 * Transpiles the JavaScript equation strings shipped in `butterchurn-presets`
 * back into MilkDrop EEL source.
 *
 * The upstream `presets/converted/*.json` payloads store preset equations only
 * as minified JavaScript (`a.zoom+=.1*a.rad*a.q1;`). MilkDrop `.milk` files
 * store them as EEL (`per_frame_1=zoom = zoom + 0.1*rad*q1;`), which is what
 * this repository's compiler, VM, and preset editor consume. Without this
 * conversion an imported preset keeps its base values and shaders but loses
 * every per-frame, per-pixel, per-point, and per-shape equation.
 *
 * The JavaScript is machine generated by butterchurn's own EEL-to-JS pass and
 * then minified, so the accepted grammar is deliberately narrow: expression
 * statements, comma sequences, assignments (including compound assignment),
 * ternaries, the usual arithmetic/comparison/logical operators, calls into a
 * fixed intrinsic set, and `a.name` / `a["name"]` / `a.megabuf[expr]` accesses.
 * Anything outside that subset (loops, local variable declarations, unknown
 * intrinsics) is reported as unsupported rather than silently mistranslated.
 */

export type TranspileResult =
  | { ok: true; statements: string[] }
  | { ok: false; reason: string };

type Token =
  | { type: 'number'; value: string }
  | { type: 'identifier'; value: string }
  | { type: 'string'; value: string }
  | { type: 'punct'; value: string }
  | { type: 'eof'; value: '' };

type Node =
  | { type: 'number'; value: number }
  | { type: 'variable'; name: string }
  | { type: 'megabuf'; buffer: 'megabuf' | 'gmegabuf'; index: Node }
  | { type: 'unary'; operator: string; operand: Node }
  | { type: 'binary'; operator: string; left: Node; right: Node }
  | { type: 'conditional'; test: Node; consequent: Node; alternate: Node }
  | { type: 'call'; name: string; args: Node[] }
  | { type: 'assign'; operator: string; target: Node; value: Node };

class TranspileError extends Error {}

